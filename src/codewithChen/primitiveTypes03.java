package codewithChen;

public class primitiveTypes03 {
    public static void main(String[] args){
        byte age = 19;
        long viewCount = 3_875_635_243L; //整数默认是int类型，写别的类型要在数字后面加标记，比如long类型加“L/l”
        //数字比较大，每三位数字用“_”隔开
        float price = 10.99F; //浮点数默认为double类型
        char letter = 'A';
        boolean isEligible = true;
    }
}
